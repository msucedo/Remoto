export type IconName = keyof typeof ICONS;

/** Names that the default deck uses but Lucide spells differently. */
const ALIASES: Record<string, IconName> = {
  'play-pause': 'play',
  trash: 'trash-2',
  home: 'house',
};

export function hasIcon(name: string): boolean {
  return name in ICONS || name in ALIASES;
}

function resolve(name: string): IconNode | null {
  if (name in ICONS) return ICONS[name as IconName];
  const alias = ALIASES[name];
  return alias ? ICONS[alias] : null;
}

/** SVG element for an icon. Unknown names draw a neutral square. */
export function icon(name: string, size = 20, cls = ''): SVGSVGElement {
  const svg = document.createElementNS(SVG_NS, 'svg');
  svg.setAttribute('xmlns', SVG_NS);
  svg.setAttribute('width', String(size));
  svg.setAttribute('height', String(size));
  svg.setAttribute('viewBox', '0 0 24 24');
  svg.setAttribute('fill', 'none');
  svg.setAttribute('stroke', 'currentColor');
  svg.setAttribute('stroke-width', '2');
  svg.setAttribute('stroke-linecap', 'round');
  svg.setAttribute('stroke-linejoin', 'round');
  svg.setAttribute('aria-hidden', 'true');
  svg.setAttribute('focusable', 'false');
  svg.setAttribute('class', `icon${cls ? ` ${cls}` : ''}`);
  const node = resolve(name) ?? ICONS.square;
  for (const [tag, attrs] of node) {
    const child = document.createElementNS(SVG_NS, tag);
    for (const [k, v] of Object.entries(attrs)) if (v !== undefined) child.setAttribute(k, String(v));
    svg.appendChild(child);
  }
  return svg;
}

