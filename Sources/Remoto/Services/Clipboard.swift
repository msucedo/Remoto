import AppKit
import Foundation
import os

/// The general pasteboard (SPEC §15.3). Pasteboard work runs on the main thread.
final class ClipboardService: Sendable {
    /// Every item of the pasteboard, every type, as raw data.
    private struct Snapshot: Sendable {
        var items: [[(String, Data)]]
        var changeCount: Int
    }

    private let sourceID: String
    private let saved = OSAllocatedUnfairLock<Snapshot?>(initialState: nil)

    init(sourceID: String) {
        self.sourceID = sourceID
    }

    func read() -> String? {
        MainThread.sync { NSPasteboard.general.string(forType: .string) }
    }

    func write(_ text: String) {
        MainThread.sync {
            let board = NSPasteboard.general
            board.clearContents()
            board.setString(text, forType: .string)
        }
    }

    /// Snapshot the pasteboard, then put `text` on it marked as transient.
    func pasteBegin(_ text: String) -> Bool {
        let sourceID = self.sourceID
        let snapshot: Snapshot? = MainThread.sync {
            let board = NSPasteboard.general
            let items = (board.pasteboardItems ?? []).map { item in
                item.types.compactMap { type in item.data(forType: type).map { (type.rawValue, $0) } }
            }
            board.clearContents()
            let item = NSPasteboardItem()
            item.setString(text, forType: .string)
            for marker in ["org.nspasteboard.TransientType", "org.nspasteboard.ConcealedType", "org.nspasteboard.AutoGeneratedType"] {
                item.setData(Data(), forType: NSPasteboard.PasteboardType(marker))
            }
            item.setString(sourceID, forType: NSPasteboard.PasteboardType("org.nspasteboard.source"))
            guard board.writeObjects([item]) else { return nil }
            return Snapshot(items: items, changeCount: board.changeCount)
        }
        saved.withLock { $0 = snapshot }
        return snapshot != nil
    }

    /// Put the snapshot back, unless something else changed the pasteboard.
    func pasteEnd() {
        guard let snapshot = saved.withLock({ s -> Snapshot? in
            defer { s = nil }
            return s
        }) else { return }
        MainThread.sync {
            let board = NSPasteboard.general
            guard board.changeCount == snapshot.changeCount else { return }
            board.clearContents()
            let items = snapshot.items.map { pairs -> NSPasteboardItem in
                let item = NSPasteboardItem()
                for (type, data) in pairs { item.setData(data, forType: NSPasteboard.PasteboardType(type)) }
                return item
            }
            if !items.isEmpty { board.writeObjects(items) }
        }
    }
}
